const expoCache = new Map<number, { disc: HTMLCanvasElement; halo: HTMLCanvasElement }>();
/** A ball exposure (volt disc, ivory rim, uv glow) and its uvDeep halo, by radius (the Chorus look, cached here). */
function ballExpo(r: number) {
  const R = Math.max(2, Math.round(r));
  let e = expoCache.get(R);
  if (e) return e;
  const size = R * 2 + 6;
  const disc = document.createElement('canvas');
  disc.width = disc.height = size;
  const g = disc.getContext('2d')!;
  const img = g.createImageData(size, size);
  const c0 = size / 2;
  for (let y = 0; y < size; y++)
    for (let x = 0; x < size; x++) {
      const dx = x + 0.5 - c0, dy = y + 0.5 - c0, d = Math.hypot(dx, dy);
      const k = (y * size + x) * 4;
      let c: readonly number[] | null = null, a = 255;
      if (d <= R - 1 && d > R - 2.2 && dx - dy > 0) c = PAL.ivory;
      else if (d <= R) c = PAL.volt;
      else if (d <= R + 2) {
        c = PAL.uv;
        a = 140;
      }
      if (!c) continue;
      img.data[k] = c[0];
      img.data[k + 1] = c[1];
      img.data[k + 2] = c[2];
      img.data[k + 3] = a;
    }
  g.putImageData(img, 0, 0);
  const halo = document.createElement('canvas');
  halo.width = halo.height = size + 16;
  const hg = halo.getContext('2d')!;
  const gr = hg.createRadialGradient(halo.width / 2, halo.height / 2, 0, halo.width / 2, halo.height / 2, halo.width / 2);
  gr.addColorStop(0, 'rgba(42,22,96,0.9)');
  gr.addColorStop(1, 'rgba(42,22,96,0)');
  hg.fillStyle = gr;
  hg.fillRect(0, 0, halo.width, halo.height);
  expoCache.set(R, (e = { disc, halo }));
  return e;
}


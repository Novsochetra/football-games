/** One Chorus-look copy of a Break west frame (volt body, ivory rim, uv glow over its uvDeep halo) at explicit alpha. */
function drawCopy(env: Env, key: SoloKey, x: number, y: number, scale: number, a: number) {
  const cv = chorusCanvas(env, key, scale, 0, -1);
  const [tx, ty] = soloTopLeft(env, key, x, y, scale, { flip: false });
  const S = Math.max(1, Math.round(scale * 4) / 4);
  const pad = (2 * scale) / S;
  const ctx = env.ctx;
  ctx.save();
  ctx.imageSmoothingEnabled = false;
  ctx.translate(x, 0);
  ctx.scale(-1, 1);
  ctx.translate(-x, 0);
  ctx.globalCompositeOperation = 'lighter';
  ctx.globalAlpha = clamp(a);
  ctx.drawImage(cv, tx - pad, ty - pad, (cv.width * scale) / S, (cv.height * scale) / S);
  ctx.restore();
}

/** The chorus wipe: volt copies of Break west at x3, x4, x5, x6 dropped on the 32nds, sweeping left -> right. */
function drawWipe(env: Env, t: number) {
  if (t < T_WIPE) return;
  const ctx = env.ctx;
  const scales = [3, 4, 5, 6];
  const xs = [70, 230, 400, 580];
  scales.forEach((s, i) => {
    const at = T_WIPE + 0.05 * i;
    if (t < at) return;
    const age = t - at;
    const a = age < 0.05 ? 0.44 : age < 0.1 ? 0.22 : 0;
    if (a <= 0) return;
    const y = 150 + 46 * s;
    // Speed lines trailing the copy (horizontal, left of it).
    ctx.save();
    ctx.globalCompositeOperation = 'lighter';
    for (let k = 0; k < 9; k++) {
      const ly = y - 20 * s - 40 * s * h01(k, i) * 1.2 + 30;
      const len = 80 + 160 * h01(k, i + 7);
      ctx.fillStyle = rgba(k % 3 ? PAL.volt : PAL.ivory, a * 0.6);
      ctx.fillRect(xs[i] - 30 - len, Math.round(ly), len, 1 + (k % 2));
    }
    ctx.restore();
    if (chorus.heroes >= chorus.maxHero) return;
    chorus.heroes++;
    drawCopy(env, 'BR2', xs[i], y, s, a);
  });
}

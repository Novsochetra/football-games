// ================================================================ 7a render

function renderGlue(env: Env, t: number, gt: number) {
  const { ctx, fx } = env;
  const c = gcamAt(t), c0 = gcamAt(Math.max(0, t - FR));
  const [sx, sy] = shakeOf(env);
  const xf: Xf = { px: BX, py: BY, z: zoomA(t), ox: sx, oy: sy };
  const S = (x: number, y: number) => toScr(xf, x, y);
  const snapK = decay(t, T_SNAP, 0.35);
  const impactF = t >= T_SNAP - 1e-6 && t < T_SNAP + 3 * FR - 1e-6;
  const L = 0.85;

  // ---- 1 · the bowl and the turf (before the dim).
  applyXf(env, xf);
  drawStandsA(ctx, c);
  drawTurfA(ctx, c);
  drawGrassA(ctx, c, c0);
  // ---- 2 · the dim: the stage is black except the roof spot's column and its pool round the ball.
  const [bxs, bys] = S(BX, TURF_Y);
  const [pvx, pvy] = S(gp(c, PIVOT[0], PIVOT[1]).x, gp(c, PIVOT[0], PIVOT[1]).y);
  const pools = [
    { x: bxs, y: bys, rx: 210 * xf.z, ry: 46 * xf.z, soft: 70, gain: 0.95 },
    { x: S(BX, 0)[0], y: S(BX, 120)[1], rx: 110 * xf.z, ry: 260 * xf.z, soft: 60, gain: 0.3 },
  ];
  if (t >= T_SNAP) pools.push({ x: pvx, y: pvy, rx: 120 * xf.z, ry: 34 * xf.z, soft: 50, gain: 0.5 * snapK + 0.25 });
  // On the impact frames the stage is struck to black round the subject: the beam prints only the ball and the boot.
  stage.dim(ctx, 0.93, impactF ? [] : pools, { max: DIM_V2 });

  // ---- 3 · lights in the dark: phone lights, fluorescent lines, glints at speed.
  applyXf(env, xf);
  drawPhonesA(ctx, c, gt, 0.95);
  ctx.save();
  ctx.globalCompositeOperation = 'lighter';
  groundLineA(ctx, c, D_ARC, 1.2, 'rgba(201,182,255,0.55)');
  groundLineA(ctx, c, BOX_LINE, 1.2, 'rgba(201,182,255,0.45)');
  ctx.restore();
  if (!impactF) drawGlintsA(ctx, c, c0, 1);

  // ---- 4 · the roof follow-spot straight down onto the ball (struck on the impact frames: only the subject blazes).
  if (!impactF) {
    stage.pillar(ctx, { x0: BX, y0: -90, x1: BX, y1: TURF_Y, w0: 54, w1: 330, a: 1, t, pumps: [0, 0.2, T_SHOW, T_SNAP, T_T3], motes: 34, seed: 71, core: 0.3 });
    stage.pool(ctx, BX, TURF_Y + 2, 190, 30, 0.9 + 0.3 * snapK);
    // The blacklight spill round the pool: saturated ultraviolet on the turf (the white core stays the ball's).
    ctx.save();
    ctx.globalCompositeOperation = 'lighter';
    drawGlow(ctx, glowOf(PAL.uv), BX, TURF_Y + 4, 300, 0.75 + 0.2 * snapK, 1, 0.16);
    ctx.restore();
  }
  stage.splash(ctx, BX, TURF_Y, 30, 200, 0.18, T_SHOW, t, 0.7);
  if (!impactF) stage.splash(ctx, BX, TURF_Y, 40, 300, 0.18, T_SNAP + 3 * FR, t, 1);

  // ---- 5 · the torn turf (world.ts gashes through the glue projector): the V gouges, the spiral divot.
  const P: Project = (x, z, h = 0) => gp(c, x, z, h);
  for (const g of GASHES) {
    if (g.id !== 'spiralC' && g.id !== 'vGouge1' && g.id !== 'vGouge2') continue;
    if (gt < g.born) continue;
    // The glue lens is its own close-up space: the spiral sits under the planted boot, the gouges either side of the turn.
    const gg = g.id === 'spiralC' ? { ...g, x: PIVOT[0], z: PIVOT[1] } : { ...g, x: g.x + (P_TURN[0] - 975), z: g.z + (P_TURN[1] - 270) };
    lightGash(ctx, gg, P, gt, { erupt: 0.8 * decay(t, T_SNAP, 0.4), shaftPx: 150 + 120 * snapK });
  }
  // The V's own wound: the hairpin torn into the turf under the exposures (a glowing furrow, out and back).
  if (t >= T_SNAP) drawVTrailA(ctx, c, t);
  env.parts.draw(ctx, 0);

  // ---- 6 · C behind the ball (the run-in, the bite), when he is still farther than the ball.
  const cs = cScreen(t);
  if (t < T_SNAP && cs.s < 24) drawCPre(env, t, false);

  // ---- 7 · the V: 12 crisp exposures along the hairpin (ball images, smearing past with the world).
  const pts: { x: number; y: number; t0: number; r: number }[] = [];
  for (const e of V_EXPO) {
    if (t < e.born) continue;
    const p = gp(c, e.x, e.z, RW);
    if (p.d < 1.5) continue;
    pts.push({ x: p.x, y: p.y, t0: e.born, r: Math.max(4, RW * p.s * 0.92) });
  }
  // Farthest first, so nearer exposures sit on top.
  pts.sort((a, b) => a.r - b.r);
  chorus.strobeChain(env, pts, t, { a: 0.8, hold: 0.24 });

  // ---- 8 · the boots and the ball.
  const boots = bootsAt(env, t, c);
  for (const b of boots) if (b.far) drawBoot(env, b, L);
  // The Chorus copy of the boot left at the turn (MB4), born at the snap where the ball turned.
  if (t >= T_SNAP) {
    const p = gp(c, P_TURN[0], P_TURN[1], RW);
    const dx = p.x - BX, dy = p.y - BY;
    const b = bootOnBall(env, 'MB4', false, dx, dy);
    drawBootCopy(env, 'MB4', false, b.x, b.y, SC, stepFade(t - T_SNAP, 0.6, 0.08));
  }
  // The wrap smear (0.767, 2 frames): a volt streak of MB5 sweeping round the far side of the ball.
  if (onFrames(t, T_SMEAR, 2)) {
    for (let i = 0; i < 4; i++) {
      const u = i / 3;
      const b = bootOnBall(env, 'MB5', false, lerp(34, 0, u), lerp(-46, 0, u));
      drawBootCopy(env, 'MB5', false, b.x, b.y, SC, 0.5 + 0.15 * i);
    }
  }
  const near = boots.filter((b) => !b.far);
  const under = near.filter((b) => BALL_UNDER[b.key]);
  const over = near.filter((b) => !BALL_UNDER[b.key]);
  for (const b of over) drawBoot(env, b, L);
  // The ball's plum shadow on the pool (the light is straight above).
  ctx.save();
  ctx.globalAlpha = 0.7;
  ctx.fillStyle = HEX.plum;
  ctx.beginPath();
  ctx.ellipse(BX, TURF_Y + 1, 40, 6, 0, 0, Math.PI * 2);
  ctx.fill();
  ctx.restore();
  // On the impact frames the halo is held in, so the beam impact prints the ball and the hooked boot as clean shapes.
  const blaze = impactF ? 0.35 : 0.85 + 0.15 * snapK + (t >= T_SHOW && t < T_SNAP ? 0.05 : 0);
  drawBall(env, spinAt(spinA(t), 0.35, -0.2, 1), BX, BY, BR, 1, 0, impactF ? 0 : 0.6, 'blacklight', squashA(t), { blaze, blazeR: impactF ? 90 : 230 + 30 * snapK });
  for (const b of under) drawBoot(env, b, L);
  env.parts.draw(ctx, 1);

  // ---- 9 · C at the lens (the lunge's leg as a soft foreground block), then the split, the pop, the print, the fall.
  if (t < T_SNAP && cs.s >= 24) drawCPre(env, t, true);
  if (t >= T_SNAP) {
    const C = printOf('C');
    const pj = cProject(t);
    const lit = t < T_POP ? 0.35 : 0.15;
    C.draw(ctx, pj, gt, { lit, noPrint: true });
    if (t >= T_POP - 1e-6) {
      const pp = pj(C.def.print.x, C.def.print.z, C.def.print.h);
      drawNeon(env, neonOf('C'), pp.x, pp.y, pp.s, clamp((t - T_POP + FR) / (3 * FR)) * lerp(1, 0.8, clamp((t - T_POP) / 0.3)), t - T_POP);
    }
  }

  // ---- 10 · light rain on the snap.
  lightRain(ctx, BX, 460, 60, T_SNAP, t, { life: 0.2, y0: -80, y1: 260, len0: 24, len1: 90, seed: 77 });

  // ---- HUD.
  env.screen();
  marqueeTag(ctx, 'ELASTICO', 30, 300, t - T_SHOW);

  // ---- post.
  soloStage(fx);
  fx.bloom = 1.0 + (t >= T_SNAP && t < T_SNAP + 0.15 ? 0.1 : 0);
  // The whips along the tangent (the ball sharp in its hole): the landing of shot 6's whip, the show, the snap.
  const streak = (s: number, dx: number, hole = 0.12) => {
    if (s <= fx.streak) return;
    fx.streak = s;
    fx.streakDX = dx;
    fx.streakDY = 0;
    const [hx, hy] = S(BX, BY);
    fx.streakHoleX = hx / VW;
    fx.streakHoleY = hy / VH;
    fx.streakHoleR = hole;
  };
  if (t < 3 * FR) streak(0.07 * (1 - t / (3 * FR)), -1);
  if (t >= T_SHOW && t < 0.5) streak(0.06 * Math.sin(Math.PI * clamp((t - T_SHOW) / 0.1)), -1);
  // The snap's whip (0.833-0.893): the world smears round the sharp ball and the hooked boot (hole R 0.17).
  if (t >= T_SNAP + 2 * FR && t < 0.9) streak(0.1 * Math.sin(Math.PI * clamp((t - T_SNAP - 2 * FR) / 0.067)), 1, 0.17);
  // The snap-back (rate 1.8, 0.88-0.95): the ball rockets across the turf, the world streams the other way.
  if (t >= 0.9 && t < 0.96) streak(0.045 * Math.sin(Math.PI * clamp((t - 0.9) / 0.06)), -1, 0.15);
  // E9 / E10: the beam impact in the roof spot's cone onto the ball.
  const cone = { x: 0.5, y: -0.05, dx: 0, dy: 1, half: 0.28 };
  if (onFrames(t, T_SNAP, 2)) soloImpact2(fx, 'A', cone);
  else if (onFrames(t, T_SNAP + 2 * FR, 1)) soloImpact2(fx, 'B', cone);
  // Flat shocks along the turf from the contact.
  const [cu, cv] = S(BX, TURF_Y - 4);
  flatShockAt(fx, cu / VW, cv / VH, T_SHOW, t, 0.02, 0.3, 0.35);
  flatShockAt(fx, cu / VW, cv / VH, T_SNAP, t, 0.05, 0.3, 0.45);
  flatShockAt(fx, cu / VW, cv / VH, T_SNAP + 0.03, t, 0.03, 0.3, 0.45);
  fx.ca = Math.max(fx.ca, 0.002 + 0.012 * decay(t, T_SNAP, 0.25));
  if (t >= T_SNAP && t < T_SNAP + 0.1) {
    fx.radial = 0.08 * (1 - (t - T_SNAP) / 0.1);
    fx.radialX = cu / VW;
    fx.radialY = (cv - 50) / VH;
  }
}

/** The hairpin torn into the turf (7a): a dark furrow with a volt core along the ball's path, out and back. */
function drawVTrailA(ctx: CanvasRenderingContext2D, c: GCam, t: number) {
  const k = clamp((t - T_SNAP) / (2 * FR));
  const pts: [number, number][] = [];
  for (let i = 0; i <= 10; i++) {
    const u = i / 10;
    pts.push([lerp(P_SHOW[0], P_TURN[0], u), lerp(P_SHOW[1], P_TURN[1], ease.outCubic(u))]);
  }
  const s = simTime(7, t);
  const back = clamp((s - S_SNAP) / (S_BACK - S_SNAP));
  for (let i = 1; i <= 8; i++) {
    const u = (i / 8) * back;
    if (u <= 0) break;
    const e = ease.outQuad(u);
    pts.push([lerp(P_TURN[0], P_BACK[0], e), lerp(P_TURN[1], P_BACK[1], e)]);
  }
  ctx.save();
  groundLineA(ctx, c, pts, 2.2, rgba([12, 6, 10], 0.9 * k));
  ctx.globalCompositeOperation = 'lighter';
  groundLineA(ctx, c, pts, 1.0, rgba(PAL.volt, 0.75 * k));
  groundLineA(ctx, c, pts, 0.35, rgba(PAL.spot, 0.6 * k * (0.6 + 0.4 * decay(t, T_SNAP, 0.3))));
  ctx.restore();
}

/** C before the snap: the run-in (silhouette -> full colour in the pool), the bite, the lunge at the lens (soft, huge). */
function drawCPre(env: Env, t: number, nearLayer: boolean) {
  if (t < 0.18) return;
  const ctx = env.ctx;
  const a = cScreen(t);
  const { pose, name } = cPose(t);
  const lit = t < 0.35 ? 0 : 0.42 * clamp((t - 0.35) / (4 * FR));
  const D0 = UNIT * a.s;
  // The hip: the pose's lowest point sits on the ground line.
  const hipY = a.gy - groundUnits(pose) * D0;
  if (!nearLayer) {
    // Mid-depth: a crisp cached puppet (k bucket) scaled nearest.
    const k = D0 >= 2.5 ? 2 : D0 >= 1.5 ? 1.5 : 1;
    // His contact shadow on the turf (the roof spot is straight above).
    ctx.save();
    ctx.globalAlpha = 0.55;
    ctx.fillStyle = HEX.void;
    ctx.beginPath();
    ctx.ellipse(a.x - 2 * a.s, a.gy, 7 * a.s, 0.9 * a.s, 0, 0, Math.PI * 2);
    ctx.fill();
    ctx.restore();
    PUPPETS.draw(ctx, name, C_KIT, pose, k, -1, a.x, hipY, D0 / k, lit, { ...DEF_SIL, lx: 0.3, ly: -1 });
    // A lilac rim of the pool's spill on his leading edge.
    return;
  }
  // At the lens: the leg blown up and softened (a small render upscaled with smoothing: out of focus), dark, rimmed.
  const r = PUPPETS.get(name + 's', C_KIT, pose, 1, -1, { ...DEF_SIL, lx: 0.3, ly: -1 });
  const D = D0;
  ctx.save();
  ctx.imageSmoothingEnabled = true;
  ctx.globalAlpha = 0.96;
  ctx.drawImage(r.cv, a.x - r.ox * D, hipY - r.oy * D, r.cv.width * D, r.cv.height * D);
  ctx.restore();
  PUPPETS.draws++;
}


/** The phone-light sea round the bowl (cylindrical: 8 px per degree of the camera's azimuth), additive after the dim. */
function drawPhonesA(ctx: CanvasRenderingContext2D, c: GCam, t: number, A: number) {
  const fwd = (c.th / DEG) + 180;
  ctx.save();
  ctx.globalCompositeOperation = 'lighter';
  for (let i = 0; i < 900; i++) {
    const az = h01(i, 1) * 360;
    let d = az - fwd;
    d = ((d % 360) + 540) % 360 - 180;
    const x = 320 - d * 8;
    if (x < -40 || x > VW + 40) continue;
    const row = h01(i, 2);
    const y = 54 + row * (HZ - 62);
    const tw = 0.6 + 0.4 * Math.sin(t * (2 + 3 * h01(i, 3)) + i);
    const col: RGB = h01(i, 4) < 0.6 ? [201, 182, 255] : h01(i, 4) < 0.85 ? [246, 240, 223] : [122, 77, 255];
    const a = (0.25 + 0.35 * h01(i, 5)) * tw * A;
    const r = 1.5 + 3 * row;
    drawGlow(ctx, glowOf(col), x, y, r * 1.8, a * 0.7);
    ctx.globalAlpha = clamp(a * 1.5);
    ctx.fillStyle = h01(i, 6) < 0.7 ? '#E2DCFF' : '#FFFAEC';
    ctx.fillRect(Math.round(x), Math.round(y), 1, 1);
  }
  ctx.globalAlpha = 1;
  ctx.restore();
}


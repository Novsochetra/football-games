/** No.10's boots at shot time t (7a). */
function bootsAt(env: Env, t: number, c: GCam): Boot[] {
  const out: Boot[] = [];
  // The swing in from behind (the left), the contact on the beat, the lift away.
  const swing = (key: SoloKey, flip: boolean, t0: number, t1: number, at: number, hold: number, leave: number, lx = 240, ly = -70) => {
    if (t < t0 || t >= t1) return;
    if (t < at) {
      const u = (t - t0) / (at - t0);
      const k = (1 - u) * (1 - u);
      out.push(bootOnBall(env, key, flip, -260 * k, -30 * k, 520 * (1 - u) * FR / (at - t0) * 60 * FR, 0));
    } else if (t < at + hold) out.push(bootOnBall(env, key, flip, 0, 0));
    else {
      const u = clamp((t - at - hold) / leave);
      const k = ease.inQuad(u);
      out.push({ ...bootOnBall(env, key, flip, lx * k, ly * k, (lx / leave) * FR * 2 * u, 0), a: 1 - 0.3 * u });
    }
  };
  // The far standing boot (MB1, the plant): a fixed world point (it travels with the turf), drawn at its own depth.
  if (t >= T_PLANT && t < T_LIFT + 0.06) {
    const p = gp(c, PIVOT[0], PIVOT[1]);
    const e = extPic(env, 'MB1', false);
    const sc = p.s >= 40 ? 2 : p.s >= 30 ? 1.5 : 1;
    const [bx, by] = soloPic(env, 'MB1').anchor('boot');
    const lift = t >= T_LIFT ? ease.inQuad((t - T_LIFT) / 0.06) : 0;
    out.push({ key: 'MB1', flip: false, x: Math.round(p.x - bx * sc), y: Math.round(p.y - (by + EXT) * sc - 60 * lift), sc, far: true, vx: 0, vy: 0, a: 1 - lift, planted: true });
    void e;
  }
  swing('MB3', false, -0.1, 0.12, 0, 0.05, 0.07, 260, -120);
  swing('MB3', true, 0.12, 0.32, 0.2, 0.05, 0.07, 260, -120);
  if (t >= 0.32 && t < T_WRAP) {
    if (t < T_SHOW) {
      const u = (t - 0.32) / 0.08;
      out.push(bootOnBall(env, 'MB4', false, -260 * (1 - u) * (1 - u), -20 * (1 - u), 9, 0));
    } else out.push(bootOnBall(env, 'MB4', false, 0, 0));
  }
  if (t >= T_WRAP && t < T_SMEAR) {
    // The wrap: the boot rolls up over the ball toward its far side.
    const u = ease.inQuad((t - T_WRAP) / (T_SMEAR - T_WRAP));
    out.push(bootOnBall(env, 'MB4', false, 34 * u, -46 * u, 6, -6));
  }
  if (t >= T_SNAP && t < 0.99) {
    if (t < 0.9) out.push(bootOnBall(env, 'MB5', false, 0, 0));
    else {
      const u = ease.inQuad(clamp((t - 0.9) / 0.09));
      out.push({ ...bootOnBall(env, 'MB5', false, -320 * u, -40 * u, -40, 0), a: 1 - 0.4 * u });
    }
  }
  swing('MB3', true, 0.93, T_CUT + 0.01, T_T3, 0.05, 0.07, 260, -120);
  return out;
}


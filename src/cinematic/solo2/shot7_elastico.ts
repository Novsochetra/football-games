/** The fake yaw psi (degrees) on the shot clock. */
function psiDeg(t: number) {
  if (t < 0.05) return -12 * (1 - ease.outCubic(t / 0.05));
  if (t < T_SHOW) return 0;
  if (t < 0.48) return 35 * ease.outQuad((t - T_SHOW) / 0.08);
  if (t < T_SNAP + 2 * FR) return 35 + 3 * ease.inOutSine(clamp((t - 0.48) / (T_SNAP - 0.48)));
  // THE SNAP's whip: -73 deg in 0.06 s, under impact B and the two frames after it (the hit-stop holds the world).
  if (t < T_SNAP + 2 * FR + 0.06) return lerp(38, -35, ease.outQuad((t - T_SNAP - 2 * FR) / 0.06));
  return lerp(-35, -20, ease.outQuad(clamp((t - T_SNAP - 2 * FR - 0.06) / 0.19)));
}

/** The simulation clock at the snap and the end of the snap-back. */
const S_SNAP = simTime(7, T_SNAP);
const S_BACK = S_SNAP + 0.12;
/** The hairpin (world): the show point, the turn (out beside C), the snap-back point. */
const P_SHOW: [number, number] = [968, 271], P_TURN: [number, number] = [976.5, 276], P_BACK: [number, number] = [985, 267.5];
/** The ball's world path on the simulation clock s. */
function ballW(s: number): [number, number] {
  if (s < 0.4) {
    // The run (6.5 m/s), nudged left by the right touch at 0.0 and right by the left touch at 0.2.
    const z = 271 - 0.8 * Math.sin(Math.PI * clamp(s / 0.2)) * (s < 0.2 ? 1 : 0) + 0.8 * Math.sin(Math.PI * clamp((s - 0.2) / 0.2)) * (s >= 0.2 ? 1 : 0);
    return [942 + 65 * s, z];
  }
  if (s < S_SNAP) {
    // The outside push: out fast, held out in the rest, carried round the turn by the wrap.
    const u = (s - 0.4) / (S_SNAP - 0.4);
    return [lerp(P_SHOW[0], P_TURN[0], u), lerp(P_SHOW[1], P_TURN[1], ease.outCubic(u))];
  }
  if (s < S_BACK) {
    const u = ease.outQuad((s - S_SNAP) / (S_BACK - S_SNAP));
    return [lerp(P_TURN[0], P_BACK[0], u), lerp(P_TURN[1], P_BACK[1], u)];
  }
  return [P_BACK[0] + 65 * (s - S_BACK), P_BACK[1] - 1.5 * (1 - Math.exp(-(s - S_BACK) / 0.1))];
}

interface GCam {
  bx: number;
  bz: number;
  th: number;
  s: number;
}
function gcamAt(t: number): GCam {
  const s = simTime(7, t);
  const [bx, bz] = ballW(s);
  return { bx, bz, th: TH0 + psiDeg(t) * DEG, s };
}
interface GP {
  x: number;
  y: number;
  s: number;
  k: number;
  d: number;
}
/** The glue projector: world (x, z, h) -> screen, for the camera orbiting the ball at azimuth th. */
function gp(c: GCam, x: number, z: number, h = 0): GP {
  const ux = Math.cos(c.th), uz = Math.sin(c.th);
  const dx = x - (c.bx + DB * ux), dz = z - (c.bz + DB * uz);
  const Z = -(dx * ux + dz * uz), X = dx * uz - dz * ux;
  const Zc = Math.max(NEAR, Z);
  const s = FG / Zc;
  return { x: BX + X * s, y: HZ + (EYE - h) * s, s, k: clamp(EYE / Zc), d: Z };
}
/** Camera-space (X across, Z depth) of a world point. */
function camXZ(c: GCam, x: number, z: number): [number, number] {
  const ux = Math.cos(c.th), uz = Math.sin(c.th);
  const dx = x - (c.bx + DB * ux), dz = z - (c.bz + DB * uz);
  return [dx * uz - dz * ux, -(dx * ux + dz * uz)];
}
/** A ground polygon (world x, z) clipped to the near plane and projected. */
function groundPoly(c: GCam, pts: readonly (readonly [number, number])[]): [number, number][] {
  const cam = pts.map(([x, z]) => camXZ(c, x, z));
  const out: [number, number][] = [];
  for (let i = 0; i < cam.length; i++) {
    const A = cam[i], B = cam[(i + 1) % cam.length];
    const ina = A[1] >= NEAR, inb = B[1] >= NEAR;
    if (ina) out.push(A);
    if (ina !== inb) {
      const u = (NEAR - A[1]) / (B[1] - A[1]);
      out.push([A[0] + (B[0] - A[0]) * u, NEAR]);
    }
  }
  return out.map(([X, Z]) => [BX + (FG * X) / Z, HZ + (FG * EYE) / Z]);
}
function fillPoly(ctx: CanvasRenderingContext2D, q: [number, number][]) {
  if (q.length < 3) return;
  ctx.beginPath();
  q.forEach((p, i) => (i ? ctx.lineTo(p[0], p[1]) : ctx.moveTo(p[0], p[1])));
  ctx.closePath();
  ctx.fill();
}


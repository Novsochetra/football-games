interface Chunk {
  sb: number;
  layer: 0 | 1 | 2;
  kind: 0 | 1 | 2;
  x0: number;
  vx: number;
  vy: number;
  size: number;
  spin: number;
  seed: number;
}
const h01 = (i: number, s: number) => {
  const v = Math.sin(i * 127.1 + s * 311.7) * 43758.5453;
  return v - Math.floor(v);
};
/** Studs x (world) at sim s before the release. */
const studsX = (s: number) => XS_CH - V_B * (s - S_CH);
const CHUNKS: Chunk[] = Array.from({ length: 100 }, (_, i) => {
  if (i < 16) {
    // The macro: turf ploughed up by his studs and thrown past the lens (big, dark, out of focus).
    const sb = 0.01 + 0.24 * h01(i, 2);
    return {
      sb, layer: 2 as const, kind: 0 as const, x0: studsX(sb) - 4 + 10 * h01(i, 5), vx: -(220 + 320 * h01(i, 6)), vy: -(140 + 260 * h01(i, 7)),
      size: 12 + 14 * h01(i, 8), spin: (h01(i, 9) - 0.5) * 12, seed: i,
    };
  }
  const r = h01(i, 1);
  const layer: 0 | 1 | 2 = r < 0.24 ? 2 : r < 0.36 ? 0 : 1;
  const sb = layer === 1 && h01(i, 10) < 0.75 ? 0.3 + 0.39 * h01(i, 2) : 0.04 + 0.62 * h01(i, 2);
  const back = h01(i, 3) < 0.28;
  return {
    sb, layer, kind: (h01(i, 4) < 0.42 ? 0 : h01(i, 4) < 0.8 ? 1 : 2) as 0 | 1 | 2,
    x0: studsX(sb) - 6 + 12 * h01(i, 5),
    vx: (back ? 1 : -1) * (40 + 300 * h01(i, 6)),
    vy: -(230 + 470 * h01(i, 7)) * (layer === 2 ? 0.8 : 1),
    size: layer === 2 ? 11 + 14 * h01(i, 8) : 5 + 6 * h01(i, 8),
    spin: (h01(i, 9) - 0.5) * 16,
    seed: i,
  };
});
const G_CHUNK = 1450;
/** A chunk's world position (subject plane) at sim s, or null before its birth or once it is down (near ones pass). */
function chunkPos(c: Chunk, s: number): [number, number, number] | null {
  const tau = s - c.sb;
  if (tau < 0) return null;
  const y = GY - 6 + c.vy * tau + 0.5 * G_CHUNK * tau * tau;
  const land = c.layer === 2 ? GY + 160 : GY + 2;
  if (y > land) return c.layer === 1 ? [c.x0 + c.vx * Math.max(0, (-c.vy + Math.sqrt(c.vy * c.vy + 2 * G_CHUNK * 8)) / G_CHUNK), GY + 2, 0] : null;
  return [c.x0 + c.vx * tau, y, c.spin * tau];
}


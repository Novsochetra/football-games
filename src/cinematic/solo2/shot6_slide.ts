function bAt(t: number): BState | null {
  if (!RS) return null;
  const name = bFrame(t);
  const i = BI[name];
  if (i === undefined) return null;
  const s = S(t);
  if (t < T_REL) {
    // Studs-led: the leading boot (studTop) slides west along the turf, the frame grounded on row 102.
    const xs = XS_CH - V_B * (s - S_CH);
    return { i, name, x: xs, y: GY, pivot: [studsOf(i)[0], SOLE], rot: 0, cs: 1 };
  }
  // Com-led after the release: flung west, the hop off the carpet, the tumble.
  const ds = s - S_FR1;
  const x = comFr1() - B_D * (1 - Math.exp(-B_K * ds));
  const w = clamp((s - S_B_UP) / (S_B_DOWN - S_B_UP));
  const lift = B_HB * 4 * w * (1 - w);
  const c = comOf(i);
  const v = clamp((s - S_B_SPIN) / (S_B_DOWN - S_B_SPIN));
  let rot = 0, cs = 1;
  if (name === 'S2c') rot = -0.35 * clamp((s - S_FR1) / (S_B_SPIN - S_FR1));
  else if (name === 'S3') {
    // Flung over: -0.35 -> -0.9 rad by the pop (broadside: the strobe photographs a readable body), then 1.86 more
    // turns with one corkscrew turn about his long axis, landing flat on his back (rot 4 pi, cs 1) at 2.10.
    const w = clamp((s - S_B_POP) / (S_B_DOWN - S_B_POP));
    if (s < S_B_POP) rot = lerp(-0.35, -0.9, clamp((s - S_B_SPIN) / (S_B_POP - S_B_SPIN)));
    else {
      rot = -0.9 - (4 * Math.PI - 0.9) * ease.outQuad(w);
      cs = Math.cos(2 * Math.PI * ease.inOutSine(w));
    }
  }
  void v;
  return { i, name, x, y: GY - SC * (SOLE - c[1]) - lift, pivot: c, rot, cs };
}

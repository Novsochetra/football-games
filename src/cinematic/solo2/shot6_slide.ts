/** The hop (sim time): the pelvis pixel index (C), one parabola from the take-off at 0.60 to the landing at 1.75. */
function pelvisAt(s: number): [number, number] {
  const u = clamp((s - S_TO) / (S_LAND - S_TO));
  return [lerp(P0[0], P1[0], u), lerp(P0[1], P1[1], u) - 4 * HOP * u * (1 - u)];
}
/** v up to a, then easing toward the cap b without reaching it (F9's reaching toe never skates on the turf). */
const softCap = (v: number, a: number, b: number) => (v <= a ? v : a + (b - a) * (1 - Math.exp(-(v - a) / (b - a))));

interface Place {
  key: SoloKey;
  /** Canvas origin (C): frame pixel (px, py) sits at world (3 (ox + px), GY + 3 (oy + py - 103)). */
  ox: number;
  oy: number;
  air: boolean;
}
function heroAt(env: Env, t: number): Place {
  const [, key, o] = seqAt(t);
  if (Number.isNaN(o)) {
    let [px, py] = pelvisAt(S(t));
    if (key === 'SL9') py = softCap(py, 55.5, 58.5);
    const [ax, ay] = soloAnchor(env, key, 'pelvis');
    return { key, ox: px - (ax - 0.5), oy: py - (ay - 0.5), air: true };
  }
  return { key, ox: o, oy: 0, air: false };
}

/** The simulation clock at shot time t (the integral of RATE[6]): frozen tableaux and slow windows in render. */
function S(t: number): number {
  if (t <= 0) return 0;
  const f = t * 60;
  const i = Math.min(NT - 1, Math.floor(f + 1e-6));
  return SIM_T[i] + (SIM_T[i + 1] - SIM_T[i]) * clamp(f - i);
}
/** The shot time at which the sim clock reaches s. */
function tOfS(s: number): number {
  for (let i = 1; i <= NT; i++) if (SIM_T[i] >= s) return (i - 1 + (s - SIM_T[i - 1]) / Math.max(1e-9, SIM_T[i] - SIM_T[i - 1])) / 60;
  return META.dur;
}

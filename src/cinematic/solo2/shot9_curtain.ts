const h01 = (i: number, s: number) => {
  const v = Math.sin(i * 127.1 + s * 311.7) * 43758.5453;
  return v - Math.floor(v);
};
const decay = (t: number, at: number, len: number) => (t < at ? 0 : 1 - ease.outQuad(clamp((t - at) / len)));
const rgba = (c: readonly number[], a: number) => `rgba(${c[0]},${c[1]},${c[2]},${clamp(a)})`;

/** The camera's trauma shake (screen px) without letting the camera transform touch the frame. */
function shakeOf(env: Env): [number, number] {
  const cam = env.cam;
  cam.zoom = 1;
  cam.rot = 0;
  cam.x = VW / 2;
  cam.y = VH / 2;
  const [u, w] = cam.toUV(cam.x, cam.y);
  return [u * VW - VW / 2, w * VH - VH / 2];
}

/** Puppet render-scale buckets (as print.ts), so the caches stay few and crisp. */
function kBucket(k: number) {
  const b = [0.25, 0.35, 0.5, 0.75, 1, 1.25, 1.5, 2, 2.5, 3, 4];
  let best = b[0];
  for (const v of b) if (Math.abs(v - k) < Math.abs(best - k)) best = v;
  return best;
}
/** Screen px per sprite px for a studio frame whose figure (98 px = 1.8 m = 18 world px) stands where s = screen px / world px. */
const SPRITE_PER_WORLD = 18 / 98;

/**
 * No.10 at any scale: nearest above 0.95, otherwise the box-filtered cache at the nearest bucket stretched to the exact
 * scale (the crane: 3.4x -> 0.25x).
 */
function drawHeroScaled(env: Env, key: SoloKey, x: number, y: number, sc: number, anchor: string) {
  if (sc >= 0.95) {
    drawSolo(env, key, x, y, sc, { anchor });
    return;
  }
  const B = [0.25, 0.33, 0.5, 0.67, 0.8];
  let b = B[0];
  for (const v of B) if (Math.abs(v - sc) < Math.abs(b - sc)) b = v;
  const ctx = env.ctx;
  ctx.save();
  ctx.translate(x, y);
  ctx.scale(sc / b, sc / b);
  drawSoloBoxed(env, key, 0, 0, b, { anchor });
  ctx.restore();
}


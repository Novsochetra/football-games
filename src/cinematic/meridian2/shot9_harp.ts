/** The story clock: the harp's hit-stop (rate 0.06 over 0.04-0.14) baked in (a pure function of t). */
const tau = (t: number) => (t < T_HIT ? t : t < T_FREEZE_END ? T_HIT + 0.06 * (t - T_HIT) : T_HIT + 0.006 + (t - T_FREEZE_END));

const hash = (n: number) => {
  const s = Math.sin(n * 127.1 + 311.7) * 43758.5453;
  return s - Math.floor(s);
};


/** The ball buries into the far top corner: the harp. */
const T_HIT = 0.04;
/** The hit-stop (rate 0.06) after the harp. */
const T_FREEZE_END = 0.14;
/** The keeper slams onto the turf. */
const T_LAND = 0.12;

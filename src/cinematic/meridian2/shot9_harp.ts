const LENS: [number, number] = [-150, 470];

/** The ball's depth behind the back net (field px) on the story clock: the cone forms, holds, lets go. */
function coneDepth(tt: number): number {
  const a = tt - T_HIT;
  if (a <= 0) return 0;
  if (a < 0.13) return 74 * ease.outCubic(a / 0.13);
  if (a < 0.24) return 74;
  return lerp(74, 16, ease.inOutQuad(clamp((a - 0.24) / 0.3)));
}
/** The ball (field x, z, h) after it buries (story clock): it presses the cone, then drops down the back net. */
function ballField(tt: number): { x: number; z: number; h: number } {
  const a = tt - T_HIT;
  const x = BACK + coneDepth(tt);
  const z = ENTRY.z + 4 * clamp(a / 0.6);
  if (a < 0.24) return { x, z, h: ENTRY.h };
  const f = a - 0.24;
  let h = ENTRY.h - 0.5 * 98 * f * f;
  if (h < 1.2) {
    // One small bounce on the turf inside the goal.
    const tl = Math.sqrt((2 * (ENTRY.h - 1.2)) / 98);
    const b = f - tl;
    h = Math.max(1.2, 1.2 + 14 * b - 49 * b * b);
  }
  return { x, z, h };
}
/** The ball on screen in 9a: [x, y, radius px]. */
function ballScreen(t: number): [number, number, number] {
  if (t < T_HIT) {
    const e = P(BACK, ENTRY.z, ENTRY.h);
    const k = ease.outQuad(clamp(t / T_HIT));
    return [lerp(62, e.x, k), lerp(262, e.y, k), lerp(21, 15, k)];
  }
  // 30 px where it buries, shrinking with depth as it bores the cone away from us.
  const b = ballField(tau(t));
  const p = P(b.x, b.z, b.h);
  return [p.x, p.y, (15 * p.s) / P(BACK, ENTRY.z, ENTRY.h).s];
}

// ---- the net's frame for this render (node screen positions, light ages)

const NN = (COLS + 1) * (ROWS + 1);
const nX = new Float32Array(NN), nY = new Float32Array(NN), nAge = new Float32Array(NN);
/** The strings' frequency (Hz, a displacement, never a brightness change): one note, so neighbouring strings ripple together. */
const STRING_HZ = 8.5;
/** GOAL!'s strum crosses the strings in this long. */
const STRUM_DUR = 0.25;

function layoutNet(t: number) {
  const tt = tau(t);
  for (let j = 0; j <= ROWS; j++)
    for (let i = 0; i <= COLS; i++) {
      const k = net.idx(i, j);
      const p = P(BACK + net.z[k], net.restX(i), net.restY(j));
      const di = Math.abs(i - IE) + Math.abs(j - JE);
      nAge[k] = t - T_HIT - di / WAVE;
      // The harp: each vertical strand rings transversely (x) from the moment the light reaches its column (story
      // clock, so the strings stay still through the hit-stop), nodes at the frame (top and bottom rows still).
      const reach = T_HIT + Math.abs(i - IE) / WAVE;
      const av = tt - tau(reach);
      let ax = 0, ay = 0;
      if (av > 0) {
        const amp = lerp(10, 4, clamp(Math.abs(i - IE) / 27)) * Math.exp(-av / 0.8) * clamp(av / 0.03);
        const sj = Math.sin((Math.PI * j) / ROWS), si = Math.sin((Math.PI * i) / COLS);
        ax = amp * sj * Math.min(1, si * 4) * Math.sin(TAU * STRING_HZ * av);
        ay = 0.22 * amp * si * sj * Math.sin(TAU * STRING_HZ * av + 1.3);
      }
      // GOAL!: the harp is strummed again, a glissando sweeping the strings left to right (0.30 -> 0.55).
      const a2 = tt - tau(T_GOAL + (i / COLS) * STRUM_DUR);
      if (a2 > 0) {
        const sj = Math.sin((Math.PI * j) / ROWS), si = Math.sin((Math.PI * i) / COLS);
        ax += 6 * Math.exp(-a2 / 0.5) * clamp(a2 / 0.03) * sj * Math.min(1, si * 4) * Math.sin(TAU * STRING_HZ * a2);
      }
      nX[k] = p.x + ax;
      nY[k] = p.y + ay;
    }
}

/** The light of a node at light-age a: 0 unlit; bucket 3 pearl (the front), 2 jade, 1 emerald. */
const bucketOf = (a: number) => (a < 0 ? 0 : a < 0.026 ? 3 : a < 0.22 ? 2 : 1);

/** The unlit net (part of the world: inked with it): back panel, roof and side netting. */
function drawNetWorld(ctx: CanvasRenderingContext2D) {
  ctx.save();
  ctx.lineWidth = 1;
  ctx.strokeStyle = 'rgba(214,226,220,0.55)';
  ctx.beginPath();
  netSegments((x0, y0, x1, y1) => {
    ctx.moveTo(x0, y0);
    ctx.lineTo(x1, y1);
  });
  ctx.stroke();
  ctx.restore();
}

/** Every strand of the net as segments (back panel, roof, side netting), with the light-age of each (the later end). */
function netSegments(fn: (x0: number, y0: number, x1: number, y1: number, age: number) => void) {
  for (let j = 0; j <= ROWS; j++)
    for (let i = 0; i <= COLS; i++) {
      const k = net.idx(i, j);
      if (i < COLS) {
        const k2 = net.idx(i + 1, j);
        fn(nX[k], nY[k], nX[k2], nY[k2], Math.min(nAge[k], nAge[k2]));
      }
      if (j < ROWS) {
        const k2 = net.idx(i, j + 1);
        fn(nX[k], nY[k], nX[k2], nY[k2], Math.min(nAge[k], nAge[k2]));
      }
    }
  // Roof netting: crossbar -> the back panel's top row, with two cross strands.
  const roofAt = (i: number, f: number): [number, number] => {
    const a = P(GX, net.restX(i), GH), k = net.idx(i, 0);
    return [lerp(a.x, nX[k], f), lerp(a.y, nY[k], f)];
  };
  for (let i = 0; i <= COLS; i++) {
    const [x0, y0] = roofAt(i, 0), [x1, y1] = roofAt(i, 1);
    fn(x0, y0, x1, y1, nAge[net.idx(i, 0)] - 0.02);
  }
  for (const f of [0.34, 0.67])
    for (let i = 0; i < COLS; i++) {
      const [x0, y0] = roofAt(i, f), [x1, y1] = roofAt(i + 1, f);
      fn(x0, y0, x1, y1, Math.min(nAge[net.idx(i, 0)], nAge[net.idx(i + 1, 0)]) - 0.02);
    }
  // Side netting: each post -> the back panel's edge column.
  for (const [col, z] of [[0, ZL], [COLS, ZR]] as const) {
    const sideAt = (j: number, f: number): [number, number] => {
      const a = P(GX, z, (net.restY(j) / BH) * GH), k = net.idx(col, j);
      return [lerp(a.x, nX[k], f), lerp(a.y, nY[k], f)];
    };
    for (let j = 0; j <= ROWS; j++) {
      const [x0, y0] = sideAt(j, 0), [x1, y1] = sideAt(j, 1);
      fn(x0, y0, x1, y1, nAge[net.idx(col, j)] - 0.02);
    }
    for (const f of [0.34, 0.67])
      for (let j = 0; j < ROWS; j++) {
        const [x0, y0] = sideAt(j, f), [x1, y1] = sideAt(j + 1, f);
        fn(x0, y0, x1, y1, Math.min(nAge[net.idx(col, j)], nAge[net.idx(col, j + 1)]) - 0.02);
      }
  }
}

/** The lit harp (light, drawn after the ink): an ink under-stroke, an emerald / mint glow and the strand colour. */
function drawNetLight(ctx: CanvasRenderingContext2D, t: number) {
  if (t < T_HIT) return;
  const fade = 1 - 0.45 * clamp((t - 0.7) / 0.4);
  const B: number[][] = [[], [], [], []];
  netSegments((x0, y0, x1, y1, age) => {
    const b = bucketOf(age);
    if (b) B[b].push(x0, y0, x1, y1);
  });
  const path = (arr: number[]) => {
    ctx.beginPath();
    for (let q = 0; q < arr.length; q += 4) {
      ctx.moveTo(arr[q], arr[q + 1]);
      ctx.lineTo(arr[q + 2], arr[q + 3]);
    }
  };
  ctx.save();
  ctx.lineCap = 'round';
  // Ink under every lit strand (the glow sits on ink, never on mid-grey).
  ctx.globalAlpha = 0.55 * fade;
  ctx.strokeStyle = HEX.ink;
  ctx.lineWidth = 3.2;
  for (let b = 1; b <= 3; b++) {
    path(B[b]);
    ctx.stroke();
  }
  ctx.globalCompositeOperation = 'lighter';
  const glow: [string, number, number][] = [['', 0, 0], [HEX.emerald, 5, 0.28], [HEX.emerald, 6, 0.42], [HEX.mint, 5, 0.32]];
  for (let b = 1; b <= 3; b++) {
    ctx.globalAlpha = glow[b][2] * fade;
    ctx.strokeStyle = glow[b][0];
    ctx.lineWidth = glow[b][1];
    path(B[b]);
    ctx.stroke();
  }
  ctx.globalCompositeOperation = 'source-over';
  const core: [string, number, number][] = [['', 0, 0], ['#18b56c', 1.3, 0.95], [HEX.jade, 1.7, 1], [HEX.pearl, 1.6, 1]];
  for (let b = 1; b <= 3; b++) {
    ctx.globalAlpha = core[b][2] * (b === 3 ? 1 : fade);
    ctx.strokeStyle = core[b][0];
    ctx.lineWidth = core[b][1];
    path(B[b]);
    ctx.stroke();
  }
  // A pearl tip on every lit knot (bright at the wave front, then a held stitch-hole).
  ctx.fillStyle = HEX.pearl;
  for (let k = 0; k < NN; k++) {
    const a = nAge[k];
    if (a < 0) continue;
    ctx.globalAlpha = a < 0.026 ? 1 : 0.55 * fade;
    const s = a < 0.026 ? 3 : 2;
    ctx.fillRect(Math.round(nX[k] - s / 2), Math.round(nY[k] - s / 2), s, s);
  }
  // GOAL!'s strum: a band of mint light sweeping the vertical strings left to right with the glissando.
  const sc = ((t - T_GOAL) / STRUM_DUR) * COLS;
  if (sc > -2 && sc < COLS + 2) {
    ctx.globalCompositeOperation = 'lighter';
    ctx.lineCap = 'round';
    for (let i = Math.max(0, Math.floor(sc - 2)); i <= Math.min(COLS, Math.ceil(sc + 1)); i++) {
      const w = 1 - Math.abs(i - sc) / 2.2;
      if (w <= 0) continue;
      ctx.beginPath();
      for (let j = 0; j <= ROWS; j++) {
        const k = net.idx(i, j);
        if (j) ctx.lineTo(nX[k], nY[k]);
        else ctx.moveTo(nX[k], nY[k]);
      }
      ctx.globalAlpha = 0.55 * w;
      ctx.strokeStyle = HEX.mint;
      ctx.lineWidth = 6;
      ctx.stroke();
      ctx.globalAlpha = 0.9 * w;
      ctx.strokeStyle = HEX.pearl;
      ctx.lineWidth = 2;
      ctx.stroke();
    }
    ctx.globalCompositeOperation = 'source-over';
  }
  // The wave front sparkles (a few knots at a time, frame-stable).
  ctx.globalCompositeOperation = 'lighter';
  for (let k = 0; k < NN; k++) {
    const a = nAge[k];
    if (a < 0 || a > 0.04 || hash(k * 3.1) > 0.22) continue;
    drawGlow(ctx, glowOf(PAL.mint), nX[k], nY[k], 8, 0.9 * (1 - a / 0.04));
  }
  ctx.restore();
}


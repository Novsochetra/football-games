/** The bridge scene (9b; held at its end framing behind the diptych). */
function renderBridge(env: Env, t: number) {
  const { ctx } = env;
  const st = env.art.stadium;
  const camY = camera9b(env, Math.min(t, 2.12));
  env.world();
  const cam = env.cam;
  // The far stand moves at half the rate of the crane (parallax).
  const bgShift = 0.5 * (camY - CAM_END.y) + SKY_DROP;
  const unpick = unpickAt(t);
  const light = 1 - 0.18 * clamp((t - T_9B) / 1.1);
  // Lamp heads catch the jade the arch lends them (smooth with distance, fading as it unpicks).
  const lampTint = [120, 620, 1120, 1620].map((tx) => {
    const hx = tx + cam.x * 0.5 - 300 + 20, hy = -26 + bgShift;
    return lampTintFor([hx, hy], ARCH, light * (1 - unpick));
  });
  ctx.save();
  ctx.translate(0, bgShift);
  drawFieldBackdrop(ctx, noStars(st), cam.x, cam.y - bgShift, 90 + t, { lampTint });
  ctx.restore();
  // The goal behind No.7, the ball resting in the far top corner's net.
  drawGoal(ctx, 'back', 0.35, 0, { u: 0.12, v: 0.15, amt: 0.6 });
  // Background: the Tower face-down in his settling dust, the three defenders staring up at the arch, the keeper.
  // (one cached image: they never move, so the frame spends no live puppet renders on them)
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(bgFigures(), BGF.x, BGF.y, BGF.w, BGF.h);
  env.parts.draw(ctx, 0);
  drawGoal(ctx, 'front', 0.35, 0);
  const pool = light * (1 - unpick);
  if (pool > 0) {
    ctx.globalCompositeOperation = 'lighter';
    for (const q of [ARCH[0], ARCH[ARCH.length - 1]]) {
      drawGlow(ctx, glowOf(PAL.emerald), q.x, q.y + 4, 90, 0.4 * pool, 1, 0.3);
      drawGlow(ctx, glowOf(PAL.jade), q.x, q.y + 2, 30, 0.35 * pool, 1, 0.35);
    }
    ctx.globalCompositeOperation = 'source-over';
  }
  // ---- the arch (light): two halves tapering to the feet, dissolving from the middle ----
  const mid = ARCH_L * 0.52;
  const gap = unpick * ARCH_L * 0.55;
  const left = archSlice(0, mid - gap), right = archSlice(mid + gap, ARCH_L).reverse();
  const al = light * (1 - 0.6 * unpick);
  if (left.length > 1) meridianStroke(ctx, left, 22 * (1 - 0.4 * unpick), { tail: 4, t, alpha: al, stars: { spacing: 34 }, cross: { every: 68 }, bristles: 6 });
  if (right.length > 1) meridianStroke(ctx, right, 22 * (1 - 0.4 * unpick), { tail: 4, t: t + 0.37, alpha: al, stars: { spacing: 34 }, cross: { every: 68 }, bristles: 6 });
  // The spark's path and its run (1.70-2.20): the passed span glows mint.
  const T = tips(env);
  const sA = archNearest(T.a[0], T.a[1]), sB = archNearest(T.b[0], T.b[1]);
  if (t >= T_SPARK && unpick < 1) {
    const k = ease.inOutSine(clamp((t - T_SPARK) / (T_ARRIVE - T_SPARK)));
    const d = lerp(sA, sB, k);
    const passed = archSlice(sA, d);
    if (passed.length > 1 && t < T_ARRIVE + 0.25) {
      const fadeP = 1 - clamp((t - T_ARRIVE) / 0.25);
      ctx.save();
      ctx.globalCompositeOperation = 'lighter';
      ctx.lineCap = 'round';
      const line = (pts: TrailPt[], w: number, col: string, a: number) => {
        ctx.strokeStyle = col;
        ctx.globalAlpha = a;
        ctx.lineWidth = w;
        ctx.beginPath();
        pts.forEach((q, i) => (i ? ctx.lineTo(q.x, q.y) : ctx.moveTo(q.x, q.y)));
        ctx.stroke();
      };
      line(passed, 14, HEX.mint, 0.4 * fadeP);
      // The comet trail: the last 90 px behind the spark burn pearl.
      const tail = archSlice(Math.max(sA, d - 90), d);
      if (tail.length > 1) {
        line(tail, 10, HEX.pearl, 0.55 * fadeP);
        line(tail, 4, '#ffffff', 0.8 * fadeP);
      }
      ctx.restore();
    }
    if (t < T_ARRIVE) {
      const q = pointAt(ARCH, ARCH_S, d);
      // Short hops from the fingertip onto the arch and off it again at the far end.
      const hopA = clamp((t - T_SPARK) / 0.05), hopB = clamp((t - (T_ARRIVE - 0.05)) / 0.05);
      const px = t < T_SPARK + 0.05 ? lerp(T.a[0], q.x, hopA) : t > T_ARRIVE - 0.05 ? lerp(q.x, T.b[0], hopB) : q.x;
      const py = t < T_SPARK + 0.05 ? lerp(T.a[1], q.y, hopA) : t > T_ARRIVE - 0.05 ? lerp(q.y, T.b[1], hopB) : q.y;
      ctx.globalCompositeOperation = 'lighter';
      drawGlow(ctx, glowOf(PAL.mint), px, py, 44, 0.75);
      drawGlow(ctx, glowOf(PAL.pearl), px, py, 16, 1);
      ctx.globalCompositeOperation = 'source-over';
      sparkle(ctx, px, py, 24, 1, t * 6);
    }
  }
  // ---- the friends (never graded) ----
  const k10 = seq(N10_SEQ, t);
  const x10 = k10.startsWith('R') ? n10X(t) : N10.x1;
  jadeRim(ctx, no10(k10), no10Anchor(env, k10, 'contact'), Math.round(x10), N10.y, 1, false, 1, 0.9 * al);
  drawNo10(env, k10, Math.round(x10), N10.y, 1, { anchor: 'contact' });
  // The Meridian Sign's fingertip trail (the tap under the eye, the sweep over the head, the point).
  if (t >= 1.4 && t < 2.0) {
    const trail: TrailPt[] = [];
    const keysMS: No10Key[] = ['MS1', 'MS3', 'MS3b', 'MS4'];
    const at = [1.4, 1.52, 1.59, 1.66];
    for (let i = 0; i < keysMS.length; i++) {
      if (t < at[i]) break;
      const [x, y] = no10Point(env, keysMS[i], 'fingertip', N10.x1, N10.y, 1, { anchor: 'contact' });
      trail.push({ x, y });
    }
    if (trail.length >= 2) threadLine(ctx, trail, 2, 1 - clamp((t - 1.75) / 0.25), { halo: 1.2 });
  }
  const k7 = seq(N7_SEQ, t);
  jadeRim(ctx, no7(k7), no7Anchor(k7, 'contact'), N7.x, N7.y, 2, true, -1, 0.9 * al);
  // The point holds 0.75 s: his drawn blink (Point Q2b) at 1.95-2.03 keeps it alive.
  const blink = k7 === 'Point.Q2' && t >= 1.95 && t < 2.03 ? no7Anim('Point') : null;
  const bi = blink ? findFrame(blink, 'Q2b') : -1;
  if (blink && bi >= 0) drawAnim(ctx, blink, null, bi, N7.x, N7.y, 2, { pivot: blink.anchorOf(bi, 'contact'), flip: true });
  else drawNo7(env, k7, N7.x, N7.y, 2, { anchor: 'contact', flip: true });
  // The spark lands on No.7's fingertip.
  if (t >= T_ARRIVE && t < T_ARRIVE + 0.4) {
    const a = t - T_ARRIVE;
    ctx.globalCompositeOperation = 'lighter';
    drawGlow(ctx, glowOf(PAL.mint), T.b[0], T.b[1], 30 * (1 - a / 0.4) + 6, 0.8 * (1 - a / 0.4));
    ctx.globalCompositeOperation = 'source-over';
    sparkle(ctx, T.b[0], T.b[1], 22 * (1 - a / 0.4) + 4, 1 - a / 0.4, Math.PI / 4);
    stitchRing(ctx, T.b[0], T.b[1], lerp(6, 46, ease.outCubic(a / 0.4)), 1 - a / 0.4, { width: 2 });
  }
  env.parts.draw(ctx, 1);
}


const ARCH_S = arcLengths(ARCH);
const ARCH_L = ARCH_S[ARCH_S.length - 1];
/** The arc length of the nearest arch point to (x, y). */
function archNearest(x: number, y: number): number {
  let best = Infinity, bd = 0;
  for (let d = 0; d <= ARCH_L; d += 2) {
    const q = pointAt(ARCH, ARCH_S, d);
    const e = Math.hypot(q.x - x, q.y - y);
    if (e < best) {
      best = e;
      bd = d;
    }
  }
  return bd;
}
/** Slice the arch between arc lengths a and b. */
function archSlice(a: number, b: number): TrailPt[] {
  const out: TrailPt[] = [];
  if (b - a < 1) return out;
  const n = Math.max(2, Math.ceil((b - a) / 8));
  for (let k = 0; k <= n; k++) {
    const q = pointAt(ARCH, ARCH_S, lerp(a, b, k / n));
    out.push({ x: q.x, y: q.y });
  }
  return out;
}

